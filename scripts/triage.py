def judge(r):
    no, role = int(r['no']), r['role']
    if role == '인쇄·홍보물': return ('—', '범위 밖', '16:9 발표 덱이 아니다')
    if role == '발표 틀': return ('—', '영감', '넘기는 덱이 아니라 자체 진행 방식(허브 · 스크롤 · 탐험)')
    if role == '표지':
        if r['motion'] == '인터랙션': return ('표지', '영감', INTER)
        return ('표지', '변주', '%s 분위기 표지. 사진 · 연출에 기대므로 생각거리로' % (r.get('family') or '중립'))
    if role == '목차·간지':
        if no in KIT_OF: return ('목차·간지·맺음', '기본 후보', '덱 키트 %s의 근거. 이미 재료로 옮겨졌다' % KIT_OF[no])
        return ('목차·간지·맺음', '변주', '%s 분위기 뼈대. 이 분위기의 덱 키트는 아직 없다' % r.get('family'))
    return BODY[no]

