groups = [('목차·간지·맺음', '목차 · 간지 · 맺음')] + [(p, p) for p, _ in PATTERNS if p not in ('목차', '간지', '맺음')] + [('—', '기본 장표에 해당 없음')]
for key, title in sorted(groups, key=lambda g: (g[0] == '—', g[0] != '표지' and g[0] != '목차·간지·맺음')):
    g = [x for x in rows if x[1] == key]
